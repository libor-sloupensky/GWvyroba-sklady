    /** Platný EAN-13 nebo EAN-8 včetně kontrolní číslice? */
    public static function jePlatny(string $ean): bool
    {
        if (!preg_match('/^(\d{8}|\d{13})$/', $ean)) {
            return false;
        }
        $soucet = 0;
        $cislice = strrev(substr($ean, 0, -1));
        for ($i = 0, $n = strlen($cislice); $i < $n; $i++) {
            $soucet += (int)$cislice[$i] * ($i % 2 === 0 ? 3 : 1);
        }
        return (10 - $soucet % 10) % 10 === (int)substr($ean, -1);
    }

    /** SVG dokument s čárovým kódem; null, pokud EAN není platný. */
    public static function svg(string $ean): ?string
    {
        if (!self::jePlatny($ean)) {
            return null;
        }
        $ean13 = strlen($ean) === 13;
        // Klidová zóna vlevo: EAN-13 má 11 modulů (je v ní první číslice), EAN-8 má 7; vpravo 7
        $vlevo = $ean13 ? 11 : 7;
        $vpravo = 7;

        // Sestavení modulů: 1 = čárka; u každého úseku příznak, zda jde o ochranné (delší) čárky
        $useky = [['101', true]];
        $leva = $ean13 ? substr($ean, 1, 6) : substr($ean, 0, 4);
        $prava = $ean13 ? substr($ean, 7) : substr($ean, 4);
        $parita = $ean13 ? self::PARITA[(int)$ean[0]] : 'LLLL';
        foreach (str_split($leva) as $i => $c) {
            $l = self::KOD_L[(int)$c];
            $useky[] = [$parita[$i] === 'L' ? $l : strrev(strtr($l, '01', '10')), false];
        }
        $useky[] = ['01010', true];
        foreach (str_split($prava) as $c) {
            $useky[] = [strtr(self::KOD_L[(int)$c], '01', '10'), false];
        }
        $useky[] = ['101', true];

        // Sousední moduly se slévají do jedné čárky (jedna cesta = čisté hrany při tisku)
        $cesta = '';
        $x = $vlevo;
        foreach ($useky as [$bity, $ochranne]) {
            $vyska = self::cislo($ochranne ? self::VYSKA_OCHRANNYCH : self::VYSKA_CAR);
            $n = strlen($bity);
            for ($i = 0; $i < $n; $i++) {
                if ($bity[$i] !== '1') {
                    continue;
                }
                $sirka = 1;
                while ($i + $sirka < $n && $bity[$i + $sirka] === '1') {
                    $sirka++;
                }
                $cesta .= 'M' . ($x + $i) . ' 0h' . $sirka . 'v' . $vyska . 'h-' . $sirka . 'z';
                $i += $sirka - 1;
            }
            $x += $n;
        }
        $sirkaCelkem = $x + $vpravo;

        // Číslice: každá vycentrovaná ve svém 7modulovém poli pod příslušným znakem
        $pole = [];
        if ($ean13) {
            $pole[] = [$ean[0], ($vlevo - 7) / 2];
        }
        foreach (str_split($leva) as $i => $c) {
            $pole[] = [$c, $vlevo + 3 + $i * 7];
        }
        foreach (str_split($prava) as $i => $c) {
            $pole[] = [$c, $vlevo + 3 + strlen($leva) * 7 + 5 + $i * 7];
        }
        $m = self::MERITKO_CISLIC;
        $cislice = '';
        foreach ($pole as [$c, $x0]) {
            $tx = $x0 + (7 - self::SIRKA_ZNAKU * $m) / 2;
            $cislice .= '<path transform="translate(' . self::cislo($tx) . ' ' . self::cislo(self::UCARI)
                . ') scale(' . $m . ' -' . $m . ')" d="' . self::CISLICE[$c] . '"/>';
        }

        $sirkaMm = self::cislo($sirkaCelkem * self::MODUL_MM);
        $vyskaMm = self::cislo(self::VYSKA * self::MODUL_MM);
        return '<?xml version="1.0" encoding="UTF-8"?>' . "\n"
            . '<svg xmlns="http://www.w3.org/2000/svg" width="' . $sirkaMm . 'mm" height="' . $vyskaMm . 'mm"'
            . ' viewBox="0 0 ' . $sirkaCelkem . ' ' . self::cislo(self::VYSKA) . '">'
            . '<title>EAN ' . $ean . '</title>'
            . '<rect width="100%" height="100%" fill="#fff"/>'
            . '<g fill="#000"><path d="' . $cesta . '"/>' . $cislice . '</g>'
            . '</svg>' . "\n";
    }

    private static function cislo(float $v): string
    {
        return rtrim(rtrim(number_format($v, 3, '.', ''), '0'), '.');
    }
